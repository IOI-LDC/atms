    public function up(): void
    {
        if (app()->environment('testing')) {
            return;
        }

        DB::table('maintenance_categories')->insertOrIgnore(
            collect(self::CATEGORIES)
                ->map(fn (string $name, string $code): array => [
                    'code' => $code,
                    'name' => $name,
                    'is_active' => true,
                    'created_at' => now(),
                    'updated_at' => now(),
                ])
                ->values()
                ->all()
        );

        $ids = DB::table('maintenance_categories')->pluck('id', 'code');
        $unclassified = $ids[MaintenanceCategory::UNCLASSIFIED_CODE];

        // Only fills assets still unclassified, so a hand-set category stays.
        // preserveKeys is required: groupBy renumbers the group otherwise.
        foreach (collect(self::ASSETS)->groupBy(fn (string $c) => $c, preserveKeys: true) as $code => $assets) {
            DB::table('assets')
                ->whereIn('erp_asset_code', $assets->keys())
                ->where('maintenance_category_id', $unclassified)
                ->update(['maintenance_category_id' => $ids[$code], 'updated_at' => now()]);
        }
    }

